// Embeds migrations/*.sql into src/db/migrations.generated.ts so the API can migrate without
// filesystem access to the SQL files (e.g. when bundled into a serverless function).
const { readdirSync, readFileSync, writeFileSync } = require('fs')
const { join } = require('path')

const dir = join(__dirname, '..', 'migrations')
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort()
const entries = files.map((f) => `  { name: ${JSON.stringify(f)}, sql: ${JSON.stringify(readFileSync(join(dir, f), 'utf8'))} },`)
writeFileSync(
  join(__dirname, '..', 'src', 'db', 'migrations.generated.ts'),
  `// Generated by scripts/embed-migrations.js from migrations/*.sql — do not edit.\nexport const MIGRATIONS: { name: string; sql: string }[] = [\n${entries.join('\n')}\n]\n`,
)
